interface Faixa {
  c1: number;
  v1: number;
  c2: number;
  v2: number;
  falante: Falante;
}

const indice = new Map<string, Faixa[]>();

function registrar(lista: FaixaBruta[], falante: Falante): void {
  for (const [codigo, c1, v1, c2, v2] of lista) {
    const faixas = indice.get(codigo) ?? [];
    faixas.push({ c1, v1, c2, v2, falante });
    indice.set(codigo, faixas);
  }
}
registrar(FALAS_JESUS, "jesus");
registrar(FALAS_DEUS, "deus");

function chave(capitulo: number, versiculo: number): number {
  return capitulo * 1000 + versiculo;
}

/** Falante do versículo inteiro, ou `null` se for narração/outra pessoa. */
export function obterFalante(
  codigoLivro: string,
  capitulo: number,
  versiculo: number,
): Falante | null {
  const faixas = indice.get(codigoLivro);
  if (!faixas) return null;
  const alvo = chave(capitulo, versiculo);
  const achada = faixas.find(
    (f) => alvo >= chave(f.c1, f.v1) && alvo <= chave(f.c2, f.v2),
  );
  return achada?.falante ?? null;
}
