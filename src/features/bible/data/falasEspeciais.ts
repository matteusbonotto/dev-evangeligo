/**
 * Faixas de "fala especial" (edição red-letter/blue-letter) para a leitura
 * bíblica (T-032, pedido explícito do usuário — item já registrado como
 * pendente em `IA/memory/project-memory.md`: "texto de Jesus em vermelho /
 * Deus em azul na leitura bíblica"). Granularidade por VERSÍCULO INTEIRO
 * (não por trecho de caractere): quando um versículo mistura narração e
 * discurso direto no mesmo versículo (comum em português, ex. "E disse
 * Jesus: ..." ou o "Eis-me aqui" de Moisés dentro do mesmo versículo do
 * chamado divino em Êxodo 3:4), o versículo inteiro recebe a cor — a
 * mesma simplificação adotada por várias edições digitais de Bíblia
 * quando a fonte de marcação não é a própria tradução exibida (ver
 * comentário de proveniência abaixo). Ver ADR (decisions.md) para a
 * decisão de escopo completa.
 *
 * FALAS_JESUS (vermelho — "red letter Bible", tradição editorial desde
 * 1899/Louis Klopsch): as 487 faixas abaixo foram extraídas
 * mecanicamente da marcação OSIS `<q who="Jesus">` do texto público-domínio
 * King James (seven1m/open-bibles, repositório "public domain and freely
 * licensed bibles"), aplicadas por NÚMERO de capítulo/versículo (não por
 * texto) — a numeração de versículo do Novo Testamento é praticamente
 * universal entre traduções/idiomas, então a mesma faixa vale para o texto
 * em português. Cobre os 4 evangelhos + Atos + 1-2 Coríntios + 1 Timóteo
 * (Paulo citando palavras de Jesus) + Apocalipse (Cristo ressurreto/
 * glorificado) — o escopo tradicional de uma "red letter Bible" impressa.
 * Verificado por amostragem contra a estrutura conhecida do texto (Sermão
 * do Monte em Mateus 5-7, Discurso de Despedida em João 14-17, cartas às 7
 * igrejas em Apocalipse 2-3, etc.) — pendente validação doutrinária formal
 * pelo agente `teologia-reformada` antes de tratar como conteúdo final
 * (mesmo padrão de pendência de ADR-007/ADR-017).
 *
 * FALAS_DEUS (azul — inspirado na "BRG Bible", edição que estende o
 * conceito de red-letter a Deus Pai): diferente de Jesus, NÃO existe uma
 * tradição editorial padronizada nem um dataset aberto equivalente para
 * "palavras de Deus Pai" (a BRG Bible é uma edição comercial sem dataset
 * público) — tentar marcar exaustivamente toda a literatura profética
 * do Antigo Testamento (onde grande parte do texto se apresenta como
 * discurso divino direto, ex. "Assim diz o Senhor") está fora do escopo
 * desta Fase 1. As 30 faixas abaixo foram curadas manualmente,
 * conferidas verso a verso contra o texto real de
 * `public/data/biblia-almeida.json`, cobrindo só os momentos mais
 * inequívocos e reconhecidos: a criação (Gênesis 1), a sarça ardente
 * (Êxodo 3), os Dez Mandamentos (Êxodo 20, Deuteronômio 5), as respostas a
 * Jó (Jó 38-41), os chamados proféticos de Isaías e Jeremias, a voz do céu
 * no batismo e na transfiguração de Jesus (nos 3 sinóticos) e a fala do
 * trono em Apocalipse 21. Expansão (principalmente a literatura profética)
 * fica para trabalho futuro, com curadoria teológica adicional — não é
 * fingir uma cobertura que não existe (mesmo padrão de honestidade sobre
 * escopo parcial já usado em outras partes da Bíblia, ex. ADR-017).
 */

