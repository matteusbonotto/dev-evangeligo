export function getLivroByCodigo(codigo: string): Livro | undefined {
  const alvo = codigo.toUpperCase();
  return LIVROS_BIBLIA.find((livro) => livro.codigo === alvo);
}

export function getLivroByOrder(order: number): Livro | undefined {
  return LIVROS_BIBLIA.find((livro) => livro.order === order);
}

/**
 * Aplica um filtro/agrupamento (T-011: "filtros por tipos"), incluindo a
 * ordem cronológica. `"harpa"` retorna vazio de propósito — a Harpa não é
 * um `Livro` (não tem capítulos/testamento/grupo); `LivrosPage` renderiza o
 * cartão dela à parte quando esse filtro está ativo.
 */
export function getLivrosFiltrados(filtro: FiltroLivros): Livro[] {
  if (filtro === "harpa") {
    return [];
  }
  if (filtro === "cronologico") {
    return ORDEM_CRONOLOGICA.map((codigo) => getLivroByCodigo(codigo)!);
  }
  if (filtro === "canonico") {
    return LIVROS_BIBLIA;
  }
  if (filtro === "AT" || filtro === "NT") {
    return LIVROS_BIBLIA.filter((livro) => livro.testamento === filtro);
  }
  return LIVROS_BIBLIA.filter((livro) => livro.grupo === filtro);
}
